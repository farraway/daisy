#!/usr/bin/env bash
# Invocation: sourced by tests/run.sh — not executed directly.
# `daisy prompt build`: include.txt names the prompts, a home prompt shadows
# the root's, `~name` takes only the `## Trigger` section, `$DAISY_ROOT` is
# substituted, a missing prompt is an error block and a warning. With a home
# name it writes <home>/AGENTS.md from anywhere; without, the workspace's
# .daisy/AGENTS.md. No commit. `daisy build` is gone (renamed, no alias).

home="$(fixture_home_dir)"
printf '# prompts\nfixfull\n~fixlazy\nfixmissing\n' > "$home/include.txt"
printf '# Full\nAt $DAISY_ROOT.\n' > "$FIXTURE_ROOT/prompts/fixfull.md"
printf '## Trigger\nthe root copy\n' > "$FIXTURE_ROOT/prompts/fixlazy.md"
mkdir -p "$home/prompts"
printf '# Lazy\n\n## Trigger\n\nWhen lazy.\n\n## Rules\n\n1. Not in AGENTS.md.\n' > "$home/prompts/fixlazy.md"
before=$(fixture_commit_count)

FIXTURE_CWD="$FIXTURE_ROOT" fixture_run build-prompt testhome
assert_eq "$RUN_EXIT" "0" "a named build exits 0 outside a workspace"
assert_contains "$RUN_STDOUT" "Built AGENTS.md for home: testhome" "reports the home"
assert_contains "$RUN_STDOUT" "Full: fixfull" "the full prompt"
assert_contains "$RUN_STDOUT" "Lazy: fixlazy" "the lazy prompt"
assert_contains "$RUN_STDERR" "Warning: Prompt not found: $FIXTURE_ROOT/prompts/fixmissing.md" "warns of the missing one"
built=$(cat "$home/AGENTS.md")
assert_contains "$built" "# This file is generated by daisy prompt build" "the header names the command"
assert_contains "$built" "# To rebuild: daisy prompt build testhome" "and how to rebuild"
assert_contains "$built" "At $FIXTURE_ROOT." "\$DAISY_ROOT substituted"
assert_contains "$built" "When lazy." "the home's trigger"
assert_not_contains "$built" "the root copy" "shadows the root's"
assert_not_contains "$built" "Not in AGENTS.md" "and nothing past the trigger"
assert_contains "$built" "# ERROR: Prompt 'fixmissing' not found" "an error block for the missing prompt"

rm -f "$FIXTURE_WORKSPACE/.daisy/AGENTS.md"
fixture_run build-prompt
assert_eq "$RUN_EXIT" "0" "the workspace build exits 0"
assert_contains "$(cat "$FIXTURE_WORKSPACE/.daisy/AGENTS.md")" "# Output: $FIXTURE_WORKSPACE/.daisy/AGENTS.md" "writes and names the workspace's file"
assert_eq "$(fixture_commit_count)" "$before" "prompt build commits nothing"

fixture_run_cli build testhome
assert_eq "$RUN_EXIT" "2" "the legacy spelling is an unknown command"
