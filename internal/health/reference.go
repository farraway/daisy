package health

import (
	"path/filepath"
	"strings"

	"daisy/internal/ops"
)

// The markers around AGENTS.md's Command Reference: everything from the
// first to the second, both lines included, is what `daisy help
// --markdown` prints.
const (
	ReferenceBegin = "<!-- BEGIN command reference: generated by `daisy help --markdown`; edit the cli table, not this block -->"
	ReferenceEnd   = "<!-- END command reference -->"
)

// ReferenceBlock is the block in text, markers included, and whether both
// markers are there.
func ReferenceBlock(text string) (string, bool) {
	begin := strings.Index(text, ReferenceBegin+"\n")
	if begin < 0 {
		return "", false
	}
	end := strings.Index(text[begin:], ReferenceEnd+"\n")
	if end < 0 {
		return "", false
	}
	return text[begin : begin+end+len(ReferenceEnd)+1], true
}

// ReferenceDrift is Check 6b: what is wrong with the root AGENTS.md's
// Command Reference against the one generated from the cli table, or ""
// when it is the same block byte for byte.
func ReferenceDrift(fs ops.FS, root, reference string) string {
	fix := "replace it with the output of 'daisy help --markdown'"
	b, err := readFile(fs, filepath.Join(root, "AGENTS.md"))
	if err != nil {
		return "AGENTS.md cannot be read, so its Command Reference cannot be checked against the cli table"
	}
	block, ok := ReferenceBlock(string(b))
	switch {
	case !ok:
		return "AGENTS.md has no Command Reference block (its BEGIN and END markers); " + fix
	case block != reference:
		return "AGENTS.md's Command Reference differs from the cli table; " + fix
	}
	return ""
}
