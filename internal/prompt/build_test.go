func write(t *testing.T, p, s string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(s), 0o644); err != nil {
		t.Fatal(err)
	}
}

// A home prompt shadows the root's of the same name; a name in neither is
// reported at the root's path, the last place looked.
func TestLookupHomeOverRoot(t *testing.T) {
	root, home := t.TempDir(), t.TempDir()
	write(t, filepath.Join(root, "prompts", "both.md"), "root")
	write(t, filepath.Join(home, "prompts", "both.md"), "home")
	write(t, filepath.Join(root, "prompts", "rootonly.md"), "root")
	os.MkdirAll(filepath.Join(home, "prompts", "dir.md"), 0o755) // not a file: passed over
	write(t, filepath.Join(root, "prompts", "dir.md"), "root")
	fs := ops.Real().FS()
	for name, want := range map[string]string{
		"both":     filepath.Join(home, "prompts", "both.md"),
		"rootonly": filepath.Join(root, "prompts", "rootonly.md"),
		"dir":      filepath.Join(root, "prompts", "dir.md"),
	} {
		if got, ok := Lookup(fs, home, root, name); !ok || got != want {
			t.Errorf("%s: %q %v", name, got, ok)
		}
	}
	if got, ok := Lookup(fs, home, root, "none"); ok || got != filepath.Join(root, "prompts", "none.md") {
		t.Errorf("none: %q %v", got, ok)
	}
}

// The trigger is the lines after `## Trigger` up to the next line that
// starts with `#`; a second `## Trigger` heading inside it is skipped, as
// awk's first rule took it.
func TestTrigger(t *testing.T) {
	for in, want := range map[string][]string{
		"# T\n\n## Trigger\n\nWhen x.\n- y\n\n## Rules\n1. r\n": {"", "When x.", "- y", ""},
		"## Trigger\nonly\n":                               {"only"},
		"## Trigger\nno newline":                           {"no newline"},
		"## Triggers\na\n#comment ends it\nb\n":            {"a"},
		"## Trigger\na\n## Trigger again\nb\n### Sub\nc\n": {"a", "b"},
		"# T\n## Rules\n":                                  nil,
		"## Trigger\n## Next\n":                            nil,
	} {
		if got := Trigger([]byte(in)); !reflect.DeepEqual(got, want) {
			t.Errorf("%q: got %q want %q", in, got, want)
		}
	}
}

// Substitution replaces the literal $DAISY_ROOT, and nothing else.
func TestSubstitute(t *testing.T) {
	got := string(Substitute([]byte("a $DAISY_ROOT/x ${DAISY_ROOT} $DAISY_ROOTS\n"), "/r"))
	if want := "a /r/x ${DAISY_ROOT} /rS\n"; got != want {
		t.Errorf("got %q want %q", got, want)
	}
}

// The whole file, against a literal: header, a full prompt (root, its last
// line without a newline), a lazy one (home, shadowing the root), a lazy one
// with no trigger (included in full, warned), a missing one (an error block,
// warned), with $DAISY_ROOT substituted throughout.
func TestBuild(t *testing.T) {
	root, home := t.TempDir(), t.TempDir()
	write(t, filepath.Join(home, "include.txt"), "# comment\n\nfull\n~lazy\n~notrig\nmissing\n")
	write(t, filepath.Join(root, "prompts", "full.md"), "# Full\nroot is $DAISY_ROOT\nend")
	write(t, filepath.Join(root, "prompts", "lazy.md"), "## Trigger\nroot copy\n")
	write(t, filepath.Join(home, "prompts", "lazy.md"), "# Lazy\n\n## Trigger\n\nWhen $DAISY_ROOT.\n\n\n## Rules\n1. r\n")
	write(t, filepath.Join(root, "prompts", "notrig.md"), "# No trigger\nbody\n")
	got, err := Build(ops.Real().FS(), Spec{
		Root: root, HomeName: "h", Home: home, Output: "/out/AGENTS.md",
		Rebuild: "daisy prompt build h", Built: time.Date(2026, 11, 1, 9, 5, 0, 0, time.UTC),
	})
	if err != nil {
		t.Fatal(err)
	}
	bar := "# ============================================================\n"
	want := "# Daisy Prompt - Auto-generated\n# Home: h\n# Built: 2026-11-01 09:05 UTC\n# Source: " + home + "/include.txt\n#\n" +
		"# This file is generated by daisy prompt build\n# Output: /out/AGENTS.md\n" +
		"# Do not edit directly - edit source prompts in prompts/ directory\n# To rebuild: daisy prompt build h\n\n" +
		bar + "# Home overrides: wherever a prompt names the root's file, read the home's\n" + bar + "\n- `" + root + "/prompts/lazy.md`: read `" + home + "/prompts/lazy.md` instead (a full override)\n" + // D49
		"\n" + bar + "# Prompt: full\n# Source: prompts/full.md\n" + bar + "\n# Full\nroot is " + root + "\nend" +
		"\n" + bar + "# Prompt: lazy (lazy - read full prompt when triggered)\n# Source: prompts/lazy.md\n" + bar + "\n\nWhen " + root + ".\n" +
		"\n" + bar + "# Prompt: notrig (WARNING: no trigger section, included in full)\n# Source: prompts/notrig.md\n" + bar + "\n# No trigger\nbody\n" +
		bar + "# ERROR: Prompt 'missing' not found\n# Expected: " + root + "/prompts/missing.md\n" + bar + "\n"
	if string(got.Text) != want {
		t.Errorf("text:\n%s\nwant:\n%s", got.Text, want)
	}
	if !reflect.DeepEqual(got.Full, []string{"full", "notrig"}) || !reflect.DeepEqual(got.Lazy, []string{"lazy"}) {
		t.Errorf("full %q lazy %q", got.Full, got.Lazy)
	}
	wantWarn := []string{
		"Warning: No ## Trigger section found in " + root + "/prompts/notrig.md\n  Include as full prompt instead, or add a ## Trigger section",
		"Warning: Prompt not found: " + root + "/prompts/missing.md",
	}
	if !reflect.DeepEqual(got.Warnings, wantWarn) {
		t.Errorf("warnings %q", got.Warnings)
	}
}

func TestBuildRefusals(t *testing.T) {
	home := t.TempDir()
	_, err := Build(ops.Real().FS(), Spec{Root: t.TempDir(), HomeName: "h", Home: home})
	if err == nil || err.Error() != "Error: "+home+"/include.txt not found\nCreate include.txt in your home directory listing prompts to include" {
		t.Errorf("no include.txt: %v", err)
	}
	write(t, filepath.Join(home, "include.txt"), "a\nit's\n")
	if _, err := Build(ops.Real().FS(), Spec{Root: t.TempDir(), HomeName: "h", Home: home}); err == nil || !strings.Contains(err.Error(), "include.txt: line 2: unmatched single quote") {
		t.Errorf("bad include.txt: %v", err)
	}
}

// Review pass 1: the bash's shell, not only its awk and sed, shaped the
// output. A root given with a trailing slash and a name holding `..` or
// `./` are concatenated, not cleaned, so the lookup and the paths printed
// are the bash's; a trigger loses its NUL bytes (command substitution) and
// one that is wholly an echo option (`-n`, `-E`, …) is what echo printed.
func TestBuildAsTheShellDid(t *testing.T) {
	root, home := t.TempDir(), t.TempDir()
	write(t, filepath.Join(root, "prompts", "a.md"), "hello\n")
	write(t, filepath.Join(root, "prompts", "n.md"), "## Trigger\n-n\n## Next\n")
	write(t, filepath.Join(root, "prompts", "e.md"), "## Trigger\n-eE\n")
	write(t, filepath.Join(root, "prompts", "z.md"), "## Trigger\nab\x00cd $DAISY\x00_ROOT\n")
	write(t, filepath.Join(home, "include.txt"), "nosuch/../a\n./a\n~n\n~e\n~z\n　# a comment\n #notcomment\n")
	got, err := Build(ops.Real().FS(), Spec{Root: root + "/", HomeName: "h", Home: home})
	if err != nil {
		t.Fatal(err)
	}
	text := string(got.Text)
	for _, want := range []string{
		"# Expected: " + root + "//prompts/nosuch/../a.md\n",
		"# Prompt: ./a\n# Source: prompts/./a.md\n" + banner + "\nhello\n",
		"# Prompt: n (lazy - read full prompt when triggered)\n# Source: prompts/n.md\n" + banner + "\n\n" + banner,
		"# Source: prompts/e.md\n" + banner + "\n\n\n" + banner,
		"# Source: prompts/z.md\n" + banner + "\nabcd $DAISY_ROOT\n", // sed ran before the NUL went
		"# ERROR: Prompt ' #notcomment' not found\n",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("missing %q in:\n%s", want, text)
		}
	}
	if strings.Contains(text, "a comment") {
		t.Errorf("a comment led by U+3000 was not skipped:\n%s", text)
	}
	if !reflect.DeepEqual(got.Lazy, []string{"n", "e", "z"}) {
		t.Errorf("lazy %q", got.Lazy)
	}
}
