// Lookup is the prompt file a name stands for, by env.Lookup: the home's
// prompts/ first, then the root's. A name with `/` or `..` is joined as it
// is: `x/../a` needs an `x`.
func Lookup(fs ops.FS, home, root, name string) (path string, ok bool) {
	return env.Lookup(fs, home, root, "prompts/"+name+".md")
}

// Trigger is the prompt's `## Trigger` section, heading excluded: the lines
// after the first line starting `## Trigger` up to the next line starting
// with `#`. A further `## Trigger` line is passed over rather than ending
// the section, as the bash's awk did.
func Trigger(data []byte) []string {
	var out []string
	found := false
	for _, line := range lines(data) {
		if strings.HasPrefix(line, "## Trigger") {
			found = true
			continue
		}
		if !found {
			continue
		}
		if strings.HasPrefix(line, "#") {
			break
		}
		out = append(out, line)
	}
	return out
}

// Substitute replaces every literal `$DAISY_ROOT` with root.
func Substitute(data []byte, root string) []byte {
	return bytes.ReplaceAll(data, []byte("$DAISY_ROOT"), []byte(root))
}

// Spec is one build: whose prompts, from which root, and what the header
// says about the file.
type Spec struct {
	Root, HomeName, Home string
	Output               string // the path the header names
	Rebuild              string // the command that rewrites Output
	Built                time.Time
}

// Built is an assembled AGENTS.md: the text, the prompts included whole
// and as triggers, in include.txt order, and the warnings for stderr.
type Built struct {
	Text       []byte
	Full, Lazy []string
	Warnings   []string
}

const banner = "# ============================================================\n"

// Build assembles AGENTS.md for s. A prompt that cannot be found becomes
// an error block in the text and a warning, and the build goes on; a lazy
// prompt without a trigger goes in whole, with a warning. The error is for
// an include.txt that is missing or malformed, or a prompt that cannot be
// read.
func Build(fs ops.FS, s Spec) (Built, error) {
	var b Built
	include := s.Home + "/include.txt"
	data, err := readRegular(fs, include)
	if err != nil {
		return b, fmt.Errorf("Error: %s not found\nCreate include.txt in your home directory listing prompts to include", include)
	}
	entries, err := ParseInclude(data)
	if err != nil {
		return b, fmt.Errorf("Error: %s: %v", include, err)
	}

	var t bytes.Buffer
	fmt.Fprintf(&t, "# Daisy Prompt - Auto-generated\n# Home: %s\n# Built: %s\n# Source: %s\n#\n", s.HomeName, s.Built.Format("2006-01-02 15:04 MST"), include)
	fmt.Fprintf(&t, "# This file is generated by daisy prompt build\n# Output: %s\n", s.Output)
	fmt.Fprintf(&t, "# Do not edit directly - edit source prompts in prompts/ directory\n# To rebuild: %s\n\n", s.Rebuild)

	for _, e := range entries {
		path, ok := Lookup(fs, s.Home, s.Root, e.Name)
		if !ok {
			b.Warnings = append(b.Warnings, "Warning: Prompt not found: "+path)
			fmt.Fprintf(&t, "%s# ERROR: Prompt '%s' not found\n# Expected: %s\n%s\n", banner, e.Name, path, banner)
			continue
		}
		body, err := fs.ReadFile(path)
		if err != nil {
			return b, fmt.Errorf("Error: cannot read %s: %v", path, err)
		}
		source := "# Source: prompts/" + e.Name + ".md\n"
		if e.Lazy {
			// In the bash's order: sed, then $(…), the empty test, echo.
			trigger := commandSubstitution(string(Substitute([]byte(strings.Join(Trigger(body), "\n")), s.Root)))
			if trigger != "" {
				fmt.Fprintf(&t, "\n%s# Prompt: %s (lazy - read full prompt when triggered)\n%s%s\n", banner, e.Name, source, banner)
				t.WriteString(echo(trigger))
				b.Lazy = append(b.Lazy, e.Name)
				continue
			}
			b.Warnings = append(b.Warnings, "Warning: No ## Trigger section found in "+path+"\n  Include as full prompt instead, or add a ## Trigger section")
			fmt.Fprintf(&t, "\n%s# Prompt: %s (WARNING: no trigger section, included in full)\n%s%s\n", banner, e.Name, source, banner)
		} else {
			fmt.Fprintf(&t, "\n%s# Prompt: %s\n%s%s\n", banner, e.Name, source, banner)
		}
		t.Write(Substitute(body, s.Root))
		b.Full = append(b.Full, e.Name)
	}
	b.Text = t.Bytes()
	return b, nil
}

// commandSubstitution is what `$(…)` kept of s: no NUL bytes, no trailing
// newlines.
func commandSubstitution(s string) string {
	return strings.TrimRight(strings.ReplaceAll(s, "\x00", ""), "\n")
}

// echoOption is an argument bash's echo takes as its options.
var echoOption = regexp.MustCompile(`^-[neE]+$`)

// echo is what bash's `echo "$s"` printed: s and a newline, unless s is
// wholly options — then nothing with -n among them, else the newline.
func echo(s string) string {
	switch {
	case !echoOption.MatchString(s):
		return s + "\n"
	case strings.Contains(s, "n"):
		return ""
	}
	return "\n"
}

// readRegular reads a regular file (or a link to one), as `[ -f ]` admits it.
func readRegular(fs ops.FS, path string) ([]byte, error) {
	fi, err := fs.Stat(path)
	if err != nil {
		return nil, err
	}
	if !fi.Mode().IsRegular() {
		return nil, fmt.Errorf("%s is not a regular file", path)
	}
	return fs.ReadFile(path)
}
