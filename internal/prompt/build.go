// Lookup is the prompt file a name stands for, by env.Lookup: the home's
// prompts/ first, then the root's. A name with `/` or `..` is joined as it
// is: `x/../a` needs an `x`.
func Lookup(fs ops.FS, home, root, name string) (path string, ok bool) {
	return env.Lookup(fs, home, root, "prompts/"+name+".md")
}

// Trigger is the prompt's `## Trigger` section, heading excluded: the lines
// after the first line starting `## Trigger` up to the next line starting
// with `#`. A further `## Trigger` line is passed over rather than ending
// the section, as the bash's awk did.
func Trigger(data []byte) []string {
	var out []string
	found := false
	for _, line := range lines(data) {
		if strings.HasPrefix(line, "## Trigger") {
			found = true
			continue
		}
		if !found {
			continue
		}
		if strings.HasPrefix(line, "#") {
			break
		}
		out = append(out, line)
	}
	return out
}

// Substitute replaces every literal `$DAISY_ROOT` with root.
func Substitute(data []byte, root string) []byte {
	return bytes.ReplaceAll(data, []byte("$DAISY_ROOT"), []byte(root))
}

// Spec is one build: whose prompts, from which root, and what the header
// says about the file.
type Spec struct {
	Root, HomeName, Home string
	Output               string // the path the header names
	Rebuild              string // the command that rewrites Output
	Built                time.Time
	// Prompts is the directory a layered prompt is materialised in, for its
	// stub to name; "" for a build with no workspace (a home's own), which
	// takes a layered prompt in whole instead.
	Prompts string
}

// Built is an assembled AGENTS.md: the text, the prompts included whole
// and as triggers, in include.txt order, the warnings for stderr, and the
// merged text of each layered prompt by the path in Spec.Prompts its stub
// names (the caller writes them with the text).
type Built struct {
	Text         []byte
	Full, Lazy   []string
	Warnings     []string
	Materialised map[string][]byte
}

const banner = "# ============================================================\n"

// Build assembles AGENTS.md for s. A prompt that cannot be found becomes
// an error block in the text and a warning, and the build goes on; a lazy
// prompt without a trigger goes in whole, with a warning. A home override
// is read as Source.Text reads it, and a lazy one's stub names the file
// that holds that text: the home's for a full override, the materialised
// merge for a layered one. The error is for an include.txt that is
// missing or malformed, or a prompt that cannot be read or merged.
func Build(fs ops.FS, s Spec) (Built, error) {
	b := Built{Materialised: map[string][]byte{}}
	include := s.Home + "/include.txt"
	data, err := readRegular(fs, include)
	if err != nil {
		return b, fmt.Errorf("Error: %s not found\nCreate include.txt in your home directory listing prompts to include", include)
	}
	entries, err := ParseInclude(data)
	if err != nil {
		return b, fmt.Errorf("Error: %s: %v", include, err)
	}

	var t bytes.Buffer
	fmt.Fprintf(&t, "# Daisy Prompt - Auto-generated\n# Home: %s\n# Built: %s\n# Source: %s\n#\n", s.HomeName, s.Built.Format("2006-01-02 15:04 MST"), include)
	fmt.Fprintf(&t, "# This file is generated by daisy prompt build\n# Output: %s\n", s.Output)
	fmt.Fprintf(&t, "# Do not edit directly - edit source prompts in prompts/ directory\n# To rebuild: %s\n\n", s.Rebuild)

	ovs, err := overrides(fs, s)
	if err != nil {
		return b, err
	}
	redirect := func(text string) string {
		for _, o := range ovs {
			if o.read != "" {
				text = strings.ReplaceAll(text, "$DAISY_ROOT/"+o.src.Rel, o.read)
			}
		}
		return text
	}
	if len(ovs) > 0 {
		fmt.Fprintf(&t, "%s# Home overrides: wherever a prompt names the root's file, read the home's\n%s\n", banner, banner)
		for _, o := range ovs {
			if o.src.Form == Layered && o.read != "" {
				b.Materialised[o.read] = o.text
			}
			switch {
			case o.read == "":
				fmt.Fprintf(&t, "- `%s`: read it, then the rules in `%s`, which follow its own (a layered override)\n", o.src.Root, o.src.Home)
			default:
				fmt.Fprintf(&t, "- `%s`: read `%s` instead (a %s override)\n", o.src.Root, o.read, o.src.Form)
			}
		}
	}

	for _, e := range entries {
		path, ok := Lookup(fs, s.Home, s.Root, e.Name)
		if !ok {
			b.Warnings = append(b.Warnings, "Warning: Prompt not found: "+path)
			fmt.Fprintf(&t, "%s# ERROR: Prompt '%s' not found\n# Expected: %s\n%s\n", banner, e.Name, path, banner)
			continue
		}
		src := Locate(fs, s.Home, s.Root, "prompts/"+e.Name+".md")
		body, err := src.Text(fs)
		if err != nil {
			return b, fmt.Errorf("Error: %v", err)
		}
		source := "# Source: prompts/" + e.Name + ".md\n"
		if e.Lazy && src.Form == Layered && s.Prompts == "" {
			fmt.Fprintf(&t, "\n%s# Prompt: %s (layered override, included in full: only a workspace build materialises it)\n%s%s\n", banner, e.Name, source, banner)
		} else if e.Lazy {
			// In the bash's order: sed, then $(…), the empty test, echo.
			trigger := commandSubstitution(string(Substitute([]byte(redirect(strings.Join(Trigger(body), "\n"))), s.Root)))
			if trigger != "" {
				fmt.Fprintf(&t, "\n%s# Prompt: %s (lazy - read full prompt when triggered)\n%s%s\n", banner, e.Name, source, banner)
				t.WriteString(echo(trigger))
				b.Lazy = append(b.Lazy, e.Name)
				continue
			}
			b.Warnings = append(b.Warnings, "Warning: No ## Trigger section found in "+path+"\n  Include as full prompt instead, or add a ## Trigger section")
			fmt.Fprintf(&t, "\n%s# Prompt: %s (WARNING: no trigger section, included in full)\n%s%s\n", banner, e.Name, source, banner)
		} else {
			fmt.Fprintf(&t, "\n%s# Prompt: %s\n%s%s\n", banner, e.Name, source, banner)
		}
		t.Write(Substitute([]byte(redirect(string(body))), s.Root))
		b.Full = append(b.Full, e.Name)
	}
	b.Text = t.Bytes()
	return b, nil
}

// commandSubstitution is what `$(…)` kept of s: no NUL bytes, no trailing
// newlines.
func commandSubstitution(s string) string {
	return strings.TrimRight(strings.ReplaceAll(s, "\x00", ""), "\n")
}

// echoOption is an argument bash's echo takes as its options.
var echoOption = regexp.MustCompile(`^-[neE]+$`)

// echo is what bash's `echo "$s"` printed: s and a newline, unless s is
// wholly options — then nothing with -n among them, else the newline.
func echo(s string) string {
	switch {
	case !echoOption.MatchString(s):
		return s + "\n"
	case strings.Contains(s, "n"):
		return ""
	}
	return "\n"
}

// readRegular reads a regular file (or a link to one), as `[ -f ]` admits it.
func readRegular(fs ops.FS, path string) ([]byte, error) {
	fi, err := fs.Stat(path)
	if err != nil {
		return nil, err
	}
	if !fi.Mode().IsRegular() {
		return nil, fmt.Errorf("%s is not a regular file", path)
	}
	return fs.ReadFile(path)
}

// override is a root prompt the home overrides: its text as the home
// reads it, and the file holding that text for an agent ("" for a layered
// one in a build with no workspace to materialise it in).
type override struct {
	src  Source
	text []byte
	read string
}

// overrides are every prompt in the home's prompts/ that overrides the
// root's, by name, included or not: a prompt may name another's file, so
// every one is redirected, and every layered one materialised.
func overrides(fs ops.FS, s Spec) ([]override, error) {
	var out []override
	for _, name := range HomePrompts(fs, s.Home) {
		src := Locate(fs, s.Home, s.Root, "prompts/"+name)
		if !src.Overridden() {
			continue
		}
		text, err := src.Text(fs)
		if err != nil {
			return nil, fmt.Errorf("Error: %v", err)
		}
		o := override{src: src, text: text, read: src.Home}
		if src.Form == Layered {
			o.read = ""
			if s.Prompts != "" {
				o.read = s.Prompts + "/" + name
			}
		}
		out = append(out, o)
	}
	return out, nil
}

// HomePrompts are the home's prompt files, by their path under prompts/.
func HomePrompts(fs ops.FS, home string) []string { return MDFiles(fs, home+"/prompts") }

// MDFiles are the *.md files under dir, by their path under it
// (subdirectories walked, as include.txt may name `team/x`), in walk
// order; dotfiles and dot-directories skipped; none for no directory.
func MDFiles(fs ops.FS, dir string) []string {
	var out []string
	var walk func(rel string)
	walk = func(rel string) {
		entries, _ := fs.ReadDir(dir + rel) // no directory, no files
		for _, en := range entries {
			if strings.HasPrefix(en.Name(), ".") {
				continue
			}
			p := strings.TrimPrefix(rel+"/"+en.Name(), "/")
			if en.IsDir() {
				walk("/" + p)
			} else if strings.HasSuffix(p, ".md") {
				out = append(out, p)
			}
		}
	}
	walk("")
	return out
}
